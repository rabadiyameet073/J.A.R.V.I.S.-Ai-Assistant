export function getStoredUiLanguage() {
    try {
        const v = localStorage.getItem(UI_LANG_KEY);
        return v && dict[v] ? v : "en";
    } catch (_) {
        return "en";
    }
}

export function storeUiLanguage(lang) {
    try { localStorage.setItem(UI_LANG_KEY, lang); } catch (_) {}
}

export function translate(lang, key, fallback = "") {
    return dict[lang]?.[key] || dict.en[key] || fallback || key;
}
